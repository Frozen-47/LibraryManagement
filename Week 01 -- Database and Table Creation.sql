-- Part A: Create the seven tables

CREATE TABLE CATEGORY (
    CATEGORY_ID INT PRIMARY KEY,
    CATEGORY_NAME VARCHAR(40) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR(100)
);

CREATE TABLE AUTHOR (
    AUTHOR_ID INT PRIMARY KEY,
    AUTHOR_NAME VARCHAR(60) NOT NULL,
    BIOGRAPHY VARCHAR(200)
);

CREATE TABLE PUBLISHER (
    PUBLISHER_ID INT PRIMARY KEY,
    PUBLISHER_NAME VARCHAR(60) NOT NULL,
    CONTACT_NO VARCHAR(15)
);

CREATE TABLE `MEMBER` (
    MEMBER_ID INT PRIMARY KEY,
    MEMBER_NAME VARCHAR(60) NOT NULL,
    EMAIL VARCHAR(80) UNIQUE,
    PHONE VARCHAR(15),
    JOIN_DATE DATE DEFAULT (CURRENT_DATE),
    MEMBER_TYPE VARCHAR(10),
    CHECK (MEMBER_TYPE IN ('STUDENT', 'STAFF'))
);

CREATE TABLE BOOK (
    BOOK_ID INT PRIMARY KEY,
    ISBN VARCHAR(20) UNIQUE,
    TITLE VARCHAR(100) NOT NULL,
    CATEGORY_ID INT,
    AUTHOR_ID INT,
    PUBLISHER_ID INT,
    PRICE DECIMAL(8,2),
    TOTAL_COPIES INT,
    AVAILABLE_COPIES INT,
    CONSTRAINT FK_BOOK_CATEGORY FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORY(CATEGORY_ID),
    CONSTRAINT FK_BOOK_AUTHOR FOREIGN KEY (AUTHOR_ID)
        REFERENCES AUTHOR(AUTHOR_ID),
    CONSTRAINT FK_BOOK_PUBLISHER FOREIGN KEY (PUBLISHER_ID)
        REFERENCES PUBLISHER(PUBLISHER_ID),
    CHECK (PRICE >= 0),
    CHECK (TOTAL_COPIES >= 0),
    CHECK (AVAILABLE_COPIES >= 0 AND AVAILABLE_COPIES <= TOTAL_COPIES)
);

CREATE TABLE BOOK_ISSUE (
    ISSUE_ID INT PRIMARY KEY,
    BOOK_ID INT,
    MEMBER_ID INT,
    ISSUE_DATE DATE,
    DUE_DATE DATE,
    RETURN_STATUS VARCHAR(10),
    CONSTRAINT FK_ISSUE_BOOK FOREIGN KEY (BOOK_ID)
        REFERENCES BOOK(BOOK_ID),
    CONSTRAINT FK_ISSUE_MEMBER FOREIGN KEY (MEMBER_ID)
        REFERENCES `MEMBER`(MEMBER_ID),
    CHECK (RETURN_STATUS IN ('ISSUED', 'RETURNED'))
);

CREATE TABLE BOOK_RETURN (
    RETURN_ID INT PRIMARY KEY,
    ISSUE_ID INT UNIQUE,
    RETURN_DATE DATE,
    FINE_AMOUNT DECIMAL(8,2),
    PAYMENT_STATUS VARCHAR(10),
    CONSTRAINT FK_RETURN_ISSUE FOREIGN KEY (ISSUE_ID)
        REFERENCES BOOK_ISSUE(ISSUE_ID),
    CHECK (FINE_AMOUNT >= 0),
    CHECK (PAYMENT_STATUS IN ('PAID', 'UNPAID'))
);


