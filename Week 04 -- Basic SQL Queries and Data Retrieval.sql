-- Week 4 - Basic SQL Queries
-- Topics: SELECT, WHERE, ORDER BY, CASE and user variables
-- Run after completing all previous weeks.

USE LibraryManagement_db;

-- Part D: Basic queries

SELECT * FROM BOOK;
SELECT TITLE, PRICE FROM BOOK;
SELECT MEMBER_NAME, EMAIL FROM `MEMBER`;

SELECT * FROM BOOK WHERE PRICE > 400;
SELECT * FROM `MEMBER` WHERE MEMBER_TYPE = 'STUDENT';
SELECT * FROM BOOK WHERE CATEGORY_ID = 1;

SELECT TITLE, PRICE FROM BOOK ORDER BY PRICE DESC;
SELECT MEMBER_NAME, JOIN_DATE FROM `MEMBER` ORDER BY JOIN_DATE ASC;

SELECT TITLE,
       CASE WHEN AVAILABLE_COPIES > 0 THEN 'AVAILABLE'
            ELSE 'NOT AVAILABLE'
       END AS STATUS
FROM BOOK;

-- Workbench uses @variables instead of Oracle's &CATEGORY_NO.
SET @CATEGORY_NO = 1;
SELECT TITLE FROM BOOK WHERE CATEGORY_ID = @CATEGORY_NO;
