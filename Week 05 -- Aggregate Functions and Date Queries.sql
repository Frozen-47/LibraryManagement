-- Week 8 - Aggregate Functions
-- Topics: COUNT, SUM, AVG, MIN, MAX, GROUP BY and HAVING
-- Run after completing all previous weeks.

USE LibraryManagement_db;

-- Part H: Aggregate functions

SELECT COUNT(*) AS TOTAL_BOOKS FROM BOOK;
SELECT COUNT(*) AS TOTAL_MEMBERS FROM `MEMBER`;
SELECT SUM(PRICE) AS TOTAL_BOOK_PRICE FROM BOOK;
SELECT AVG(PRICE) AS AVERAGE_PRICE FROM BOOK;
SELECT MAX(PRICE) AS HIGHEST_PRICE, MIN(PRICE) AS LOWEST_PRICE FROM BOOK;

SELECT CATEGORY_ID, COUNT(*) AS TOTAL_BOOKS
FROM BOOK
GROUP BY CATEGORY_ID;

SELECT CATEGORY_ID, COUNT(*) AS TOTAL_BOOKS
FROM BOOK
GROUP BY CATEGORY_ID
HAVING COUNT(*) > 1;

-- Week 10 - Date and Fine Queries
-- Topics: Date filtering, overdue-day calculation and fine totals
-- Run after completing all previous weeks.

USE LibraryManagement_db;

-- Part J: Date and fine queries

SELECT *
FROM BOOK_ISSUE
WHERE ISSUE_DATE >= '2026-10-01'
  AND ISSUE_DATE < '2026-11-01';

SELECT ISSUE_ID, DUE_DATE,
       GREATEST(DATEDIFF(CURRENT_DATE, DUE_DATE), 0) AS OVERDUE_DAYS
FROM BOOK_ISSUE
WHERE RETURN_STATUS = 'ISSUED';

SELECT SUM(FINE_AMOUNT) AS TOTAL_FINE
FROM BOOK_RETURN
WHERE PAYMENT_STATUS = 'PAID';

