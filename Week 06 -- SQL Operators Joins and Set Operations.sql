USE LibraryManagement_db;

-- Part E: Operators

SELECT TITLE, PRICE FROM BOOK WHERE PRICE BETWEEN 300 AND 700;
SELECT TITLE FROM BOOK WHERE CATEGORY_ID IN (1, 2);
SELECT TITLE FROM BOOK WHERE TITLE LIKE 'O%';
SELECT TITLE FROM BOOK WHERE TITLE LIKE '%Programming%';
SELECT MEMBER_NAME FROM `MEMBER` WHERE EMAIL IS NULL;

