-- Week 6 - SQL Joins
-- Topics: INNER, LEFT, RIGHT, FULL OUTER JOIN equivalent, SELF, NATURAL and CROSS JOIN
-- Run after completing all previous weeks.

USE LibraryManagement_db;

-- Part F: Joins

SELECT I.ISSUE_ID, M.MEMBER_NAME, B.TITLE
FROM BOOK_ISSUE I
INNER JOIN `MEMBER` M ON I.MEMBER_ID = M.MEMBER_ID
INNER JOIN BOOK B ON I.BOOK_ID = B.BOOK_ID;

SELECT M.MEMBER_ID, M.MEMBER_NAME, I.ISSUE_ID
FROM `MEMBER` M
LEFT JOIN BOOK_ISSUE I ON M.MEMBER_ID = I.MEMBER_ID;

SELECT M.MEMBER_NAME, I.ISSUE_ID
FROM `MEMBER` M
RIGHT JOIN BOOK_ISSUE I ON M.MEMBER_ID = I.MEMBER_ID;

-- MySQL has no FULL OUTER JOIN; combine left and right joins.
SELECT M.MEMBER_NAME, I.ISSUE_ID
FROM `MEMBER` M
LEFT JOIN BOOK_ISSUE I ON M.MEMBER_ID = I.MEMBER_ID
UNION
SELECT M.MEMBER_NAME, I.ISSUE_ID
FROM `MEMBER` M
RIGHT JOIN BOOK_ISSUE I ON M.MEMBER_ID = I.MEMBER_ID;

SELECT B1.TITLE AS BOOK_ONE, B2.TITLE AS BOOK_TWO
FROM BOOK B1
JOIN BOOK B2
  ON B1.CATEGORY_ID = B2.CATEGORY_ID
 AND B1.BOOK_ID < B2.BOOK_ID;

SELECT CATEGORY_NAME, TITLE
FROM CATEGORY NATURAL JOIN BOOK;

SELECT CATEGORY_NAME, AUTHOR_NAME
FROM CATEGORY CROSS JOIN AUTHOR;

-- Week 7 - Set Operators
-- Topics: UNION, UNION ALL, and EXISTS / NOT EXISTS equivalents
-- Run after completing all previous weeks.

USE LibraryManagement_db;

-- Part G: Set operators

SELECT 
    MEMBER_ID
FROM
    BOOK_ISSUE 
UNION SELECT 
    I.MEMBER_ID
FROM
    BOOK_RETURN R
        JOIN
    BOOK_ISSUE I ON R.ISSUE_ID = I.ISSUE_ID;

SELECT MEMBER_ID FROM BOOK_ISSUE
UNION ALL
SELECT I.MEMBER_ID
FROM BOOK_RETURN R
JOIN BOOK_ISSUE I ON R.ISSUE_ID = I.ISSUE_ID;

-- INTERSECT equivalent: members who issued and returned books.
SELECT DISTINCT I.MEMBER_ID
FROM BOOK_ISSUE I
WHERE EXISTS (
    SELECT 1
    FROM BOOK_RETURN R
    WHERE R.ISSUE_ID = I.ISSUE_ID
);

-- MINUS equivalent: members who issued books but have not returned any.
SELECT DISTINCT I.MEMBER_ID
FROM BOOK_ISSUE I
WHERE NOT EXISTS (
    SELECT 1
    FROM BOOK_RETURN R
    WHERE R.ISSUE_ID = I.ISSUE_ID
);

-- Set operations using ISSUE_ID
SELECT ISSUE_ID FROM BOOK_ISSUE
UNION
SELECT ISSUE_ID FROM BOOK_RETURN;

SELECT I.ISSUE_ID
FROM BOOK_ISSUE I
WHERE EXISTS (
    SELECT 1 FROM BOOK_RETURN R WHERE R.ISSUE_ID = I.ISSUE_ID
);

SELECT I.ISSUE_ID
FROM BOOK_ISSUE I
WHERE NOT EXISTS (
    SELECT 1 FROM BOOK_RETURN R WHERE R.ISSUE_ID = I.ISSUE_ID
);
